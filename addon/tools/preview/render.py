#!/usr/bin/env python3
"""Paint a hearth-board layout dumped by preview.lua.

    python3 addon/tools/preview/render.py scene.json out.png [scale]

Fonts are stand-ins: Noto Serif for Friz Quadrata, Noto Serif Bold for
Morpheus. Pixel snapping is not modelled.
"""
import json
import os
import sys

import numpy as np
from PIL import Image, ImageDraw, ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
ADDON = os.path.join(HERE, "..", "..", "Eldgrim")
FONTS = {
    "body": "/usr/share/fonts/google-noto/NotoSerif-Regular.ttf",
    "title": "/usr/share/fonts/google-noto/NotoSerif-Bold.ttf",
}
_tex = {}
_font = {}


def texture(path):
    name = path.replace("\\", "/").split("/")[-1]
    if name not in _tex:
        _tex[name] = Image.open(os.path.join(ADDON, name + ".tga")).convert("RGBA")
    return _tex[name]


def font(item, scale):
    kind = "title" if "MORPHEUS" in (item.get("font") or "").upper() else "body"
    # Friz Quadrata sits larger on its size than Noto Serif.
    size = max(6, int(round(item["size"] * scale * (1.0 if kind == "title" else 1.02))))
    key = (kind, size)
    if key not in _font:
        _font[key] = ImageFont.truetype(FONTS[kind], size)
    return _font[key]


def wrap(text, fnt, width):
    lines = []
    for para in text.split("\n"):
        line = ""
        for word in para.split(" "):
            trial = (line + " " + word) if line else word
            if width and fnt.getlength(trial) > width and line:
                lines.append(line)
                line = word
            else:
                line = trial
        lines.append(line)
    return lines


def write_metrics(path):
    """Character advances of the body font, for preview.lua's layout."""
    fnt = ImageFont.truetype(FONTS["body"], 100)
    rows = []
    for code in range(32, 127):
        ch = chr(code)
        rows.append("[%s]=%.4f" % (json.dumps(ch).replace("\\/", "/"), fnt.getlength(ch) / 100 * 1.02))
    with open(path, "w") as fh:
        fh.write("-- Generated by render.py --metrics. Do not edit.\nreturn { body = {" + ",".join(rows) + "} }\n")


def main():
    if sys.argv[1] == "--metrics":
        write_metrics(sys.argv[2])
        return
    data = json.load(open(sys.argv[1]))
    out = sys.argv[2]
    scale = float(sys.argv[3]) if len(sys.argv) > 3 else 1.5
    W, H = data["width"], data["height"]
    canvas = Image.new("RGBA", (int(W * scale), int(H * scale)), (34, 38, 44, 255))
    # A plain backdrop so the window's edges are visible.
    bd = ImageDraw.Draw(canvas)
    for y in range(0, canvas.height, int(40 * scale)):
        bd.line([(0, y), (canvas.width, y)], fill=(40, 44, 51, 255))

    def box(rect):
        l, b, r, t = rect
        return (l * scale, (H - t) * scale, r * scale, (H - b) * scale)

    for item in data["items"]:
        x0, y0, x1, y1 = box(item["rect"])
        if x1 - x0 < 0.01 or y1 - y0 < 0.01:
            if item["kind"] == "Texture":
                continue
        layer = Image.new("RGBA", canvas.size, (0, 0, 0, 0))
        alpha = item.get("alpha", 1)
        if item["kind"] == "Texture":
            ix0, iy0 = int(round(x0)), int(round(y0))
            ix1, iy1 = max(ix0 + 1, int(round(x1))), max(iy0 + 1, int(round(y1)))
            w, h = ix1 - ix0, iy1 - iy0
            if item.get("color"):
                r, g, b, a = item["color"]
                patch = Image.new("RGBA", (w, h), (int(r * 255), int(g * 255), int(b * 255), int(a * 255)))
            elif item.get("file"):
                src = texture(item["file"])
                l, r, t, b = item.get("coords") or (0, 1, 0, 1)
                sw, sh = src.size
                crop = src.crop((min(l, r) * sw, min(t, b) * sh, max(l, r) * sw, max(t, b) * sh))
                if l > r:
                    crop = crop.transpose(Image.FLIP_LEFT_RIGHT)
                if t > b:
                    crop = crop.transpose(Image.FLIP_TOP_BOTTOM)
                patch = crop.resize((w, h), Image.BILINEAR)
                arr = np.asarray(patch).astype(np.float64) / 255
                if item.get("desaturated"):
                    grey = arr[..., :3].mean(axis=2, keepdims=True)
                    arr[..., :3] = grey
                if item.get("vertex"):
                    arr *= np.array(item["vertex"])
                patch = Image.fromarray((np.clip(arr, 0, 1) * 255).astype(np.uint8), "RGBA")
            else:
                continue
            if alpha < 1:
                a = np.asarray(patch).copy()
                a[..., 3] = (a[..., 3] * alpha).astype(np.uint8)
                patch = Image.fromarray(a, "RGBA")
            if item.get("blend") == "ADD":
                base = np.asarray(canvas).astype(np.float64)
                add = np.zeros_like(base)
                p = np.asarray(patch).astype(np.float64)
                region = add[max(iy0, 0):iy1, max(ix0, 0):ix1]
                pp = p[max(0, -iy0):max(0, -iy0) + region.shape[0], max(0, -ix0):max(0, -ix0) + region.shape[1]]
                region[..., :3] = pp[..., :3] * (pp[..., 3:4] / 255)
                if item.get("clip"):
                    cx0, cy0, cx1, cy1 = [int(v) for v in box(item["clip"])]
                    m = np.zeros(add.shape[:2], bool)
                    m[max(cy0, 0):cy1, max(cx0, 0):cx1] = True
                    add[~m] = 0
                base[..., :3] = np.clip(base[..., :3] + add[..., :3], 0, 255)
                canvas = Image.fromarray(base.astype(np.uint8), "RGBA")
                continue
            layer.paste(patch, (ix0, iy0))
        else:
            fnt = font(item, scale)
            text = item.get("text") or ""
            r, g, b = item["color"][:3]
            colour = (int(r * 255), int(g * 255), int(b * 255), int(255 * alpha))
            draw = ImageDraw.Draw(layer)
            if item["kind"] == "EditBox":
                ex0 = x0
                line_h = fnt.size * 1.2
                if item.get("multiLine"):
                    lines = wrap(text, fnt, x1 - x0)
                    ty = y0
                else:
                    lines = [text]
                    ty = (y0 + y1) / 2 - line_h / 2
                for line in lines:
                    draw.text((ex0, ty), line, font=fnt, fill=colour)
                    ty += line_h
                if item.get("focus"):
                    last = lines[-1] if lines else ""
                    cx = ex0 + fnt.getlength(last) + 1
                    cy = ty - line_h
                    draw.line([(cx, cy + 2), (cx, cy + line_h - 1)], fill=(255, 240, 200, 255), width=max(1, int(scale)))
            else:
                width = x1 - x0
                lines = wrap(text, fnt, width if item.get("wrap") and not item.get("autoWidth") else None)
                if not item.get("wrap") and not item.get("autoWidth") and fnt.getlength(lines[0]) > width > 0:
                    t = lines[0]
                    while t and fnt.getlength(t + "...") > width:
                        t = t[:-1]
                    lines = [t + "..."]
                line_h = fnt.size * 1.22 + item.get("spacing", 0) * scale
                total = line_h * len(lines)
                jv = item.get("justifyV")
                if jv == "MIDDLE":
                    ty = (y0 + y1) / 2 - total / 2
                elif jv == "BOTTOM":
                    ty = y1 - total
                else:
                    ty = y0
                for line in lines:
                    lw = fnt.getlength(line)
                    jh = item.get("justifyH")
                    if jh == "CENTER":
                        tx = (x0 + x1) / 2 - lw / 2
                    elif jh == "RIGHT":
                        tx = x1 - lw
                    else:
                        tx = x0
                    draw.text((tx + scale, ty + scale), line, font=fnt, fill=(0, 0, 0, int(220 * alpha)))
                    draw.text((tx, ty), line, font=fnt, fill=colour)
                    ty += line_h
        if item.get("clip"):
            cx0, cy0, cx1, cy1 = box(item["clip"])
            mask = Image.new("L", canvas.size, 0)
            ImageDraw.Draw(mask).rectangle((cx0, cy0, cx1 - 1, cy1 - 1), fill=255)
            la = np.asarray(layer).copy()
            la[..., 3] = (la[..., 3].astype(np.float64) * (np.asarray(mask) / 255)).astype(np.uint8)
            layer = Image.fromarray(la, "RGBA")
        canvas.alpha_composite(layer)
    canvas.convert("RGB").save(out)
    print("wrote", out)


if __name__ == "__main__":
    main()
